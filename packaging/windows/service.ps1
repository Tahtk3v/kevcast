# Manages the KevCast Server background service on Windows. Called by the KevCast installers.
#   service.ps1 -Action install   -ServerDir "C:\Program Files\KevCast\Server" [-Port 8080] [-DataDir C:\ProgramData\KevCast]
#   service.ps1 -Action stop|start|uninstall -ServerDir ...
# The service is a Task Scheduler task that starts at boot as SYSTEM and restarts on failure.
param(
  [Parameter(Mandatory)][ValidateSet('install', 'uninstall', 'stop', 'start')][string]$Action,
  [Parameter(Mandatory)][string]$ServerDir,
  [int]$Port = 0,
  [string]$DataDir = "$env:ProgramData\KevCast"
)
$ErrorActionPreference = 'Stop'
$TaskName = 'KevCast Server'
$Launcher = Join-Path $ServerDir 'kevcast-server.cmd'

function Stop-KevCast {
  Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
  # Stopping the task ends cmd.exe; make sure the node.exe it started is gone too.
  $node = (Join-Path $ServerDir 'node\node.exe').ToLower()
  Get-CimInstance Win32_Process -Filter "Name='node.exe'" -ErrorAction SilentlyContinue |
    Where-Object { $_.ExecutablePath -and $_.ExecutablePath.ToLower() -eq $node } |
    ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }
}

switch ($Action) {
  'stop' { Stop-KevCast }
  'start' { Start-ScheduledTask -TaskName $TaskName }
  'uninstall' {
    Stop-KevCast
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue
    Remove-NetFirewallRule -DisplayName 'KevCast' -ErrorAction SilentlyContinue
    Remove-NetFirewallRule -DisplayName 'KevCast discovery' -ErrorAction SilentlyContinue
  }
  'install' {
    Stop-KevCast
    # Keep the port of an earlier installation unless a new one is given.
    if ($Port -eq 0) {
      $Port = 8080
      if (Test-Path $Launcher) {
        $m = Select-String -Path $Launcher -Pattern '^set PORT=(\d+)' | Select-Object -First 1
        if ($m) { $Port = [int]$m.Matches[0].Groups[1].Value }
      }
    }
    New-Item -ItemType Directory -Force -Path $DataDir | Out-Null
    @"
@echo off
rem KevCast Server launcher (generated by the installer). Change PORT here, then restart the
rem "KevCast Server" task in Task Scheduler.
set PORT=$Port
set KEVCAST_DATA=$DataDir
set PDFTOPPM_PATH=$ServerDir\poppler\pdftoppm.exe
cd /d "$ServerDir\app"
"$ServerDir\node\node.exe" server\index.js >> "$DataDir\kevcast.log" 2>&1
"@ | Set-Content -Path $Launcher -Encoding ASCII

    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue
    $action = New-ScheduledTaskAction -Execute 'cmd.exe' -Argument "/c `"$Launcher`""
    $trigger = New-ScheduledTaskTrigger -AtStartup
    $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
      -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1)
    $principal = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
    Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings -Principal $principal `
      -Description 'KevCast narrowcasting server' | Out-Null

    Remove-NetFirewallRule -DisplayName 'KevCast' -ErrorAction SilentlyContinue
    Remove-NetFirewallRule -DisplayName 'KevCast discovery' -ErrorAction SilentlyContinue
    New-NetFirewallRule -DisplayName 'KevCast' -Direction Inbound -Protocol TCP -LocalPort $Port -Action Allow -Profile Domain, Private | Out-Null
    New-NetFirewallRule -DisplayName 'KevCast discovery' -Direction Inbound -Protocol UDP -LocalPort 41234 -Action Allow -Profile Domain, Private | Out-Null

    Start-ScheduledTask -TaskName $TaskName
    # Wait (max 30 s) until the server answers, so the shortcuts work right after setup.
    for ($i = 0; $i -lt 30; $i++) {
      try { Invoke-WebRequest -UseBasicParsing -TimeoutSec 2 "http://localhost:$Port/api/session" | Out-Null; break } catch { Start-Sleep -Seconds 1 }
    }
    # Tell the installer which port is in use (it writes the shortcuts).
    Set-Content -Path (Join-Path $ServerDir 'port.txt') -Value $Port -Encoding ASCII
  }
}
